//! Lists which OpenBLAS source each core uses for each `axpy` precision, and
//! whether that source is assembly or C.
//!
//!     OPENBLAS=<checkout> zig run tools/blas_asm/survey.zig [-- gemm]
//!
//! With `gemm`, lists the `gemm` kernel, beta and packing (copy) sources instead,
//! from the defaults of `Makefile.L3`.
//!
//! Reads `kernel/<arch>/KERNEL.<core>`, falling back to `kernel/<arch>/KERNEL`
//! and then to the defaults in `kernel/Makefile.L1`, as the build does. A core
//! that assigns a kernel under a conditional lists every alternative, joined
//! by `|`; which one applies depends on the compiler or byte order.

const std = @import("std");
const Io = std.Io;
const map = @import("kernel_map.zig");

/// `kernel/` subdirectories with their own kernel lists.
const arches = [_][]const u8{
    "x86_64",  "x86",         "arm64", "arm",   "power", "mips64", "mips",
    "riscv64", "loongarch64", "zarch", "sparc", "alpha", "ia64",   "wasm",
};

/// The precisions in `Makefile.L1`: real, double, complex, double complex,
/// then the extended-precision pair.
const funcs = [_][]const u8{ "S", "D", "C", "Z", "Q", "X" };

fn join(parts: []const []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (parts, 0..) |p, i| {
        if (i > 0) try out.appendSlice(map.arena, " \\| ");
        try out.append(map.arena, '`');
        try out.appendSlice(map.arena, p);
        try out.append(map.arena, '`');
    }
    return out.items;
}

fn isAsm(name: []const u8) bool {
    return std.mem.endsWith(u8, name, ".S");
}

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const checkout = init.environ_map.get("OPENBLAS") orelse
        map.die("set OPENBLAS to the OpenBLAS checkout", .{});
    try map.init(arena, init.io, checkout);

    var args = try init.minimal.args.iterateAllocator(arena);
    _ = args.next();
    if (args.next()) |mode| {
        if (std.mem.eql(u8, mode, "gemm")) return try gemm(init, arena);
        map.die("unknown survey '{s}'", .{mode});
    }

    var w: std.ArrayList(u8) = .empty;
    try w.appendSlice(arena,
        \\# `axpy` kernel coverage
        \\
        \\Generated by `tools/blas_asm/survey.zig` from OpenBLAS `kernel/`; re-derive
        \\it rather than editing it. Each cell is the source that core's `KERNEL.<core>`
        \\selects, falling back to the architecture's `KERNEL`, then to the
        \\`Makefile.L1` default. `|` separates alternatives chosen by a conditional
        \\(compiler version or byte order). `CC`, `ZC` and `XC` use the same source
        \\as `C`, `Z` and `X`.
        \\
        \\
    );

    // every distinct (architecture, source), for the totals
    var seen: std.StringArrayHashMapUnmanaged(bool) = .empty;

    for (arches) |arch| {
        const cores = try map.cores(arch) orelse continue;
        try w.print(arena, "## {s}\n\n| core | S | D | C | Z | Q | X |\n|---|---|---|---|---|---|---|\n", .{arch});
        for (cores) |core| {
            try w.print(arena, "| {s} |", .{core});
            for (funcs) |f| {
                const v = try map.resolve(arch, core, f);
                for (v) |s| try seen.put(arena, try std.fmt.allocPrint(arena, "{s}/{s}", .{ arch, s }), isAsm(s));
                try w.print(arena, " {s} |", .{try join(v)});
            }
            try w.append(arena, '\n');
        }
        try w.append(arena, '\n');
    }

    var n_asm: usize = 0;
    for (seen.values()) |is_asm| {
        if (is_asm) n_asm += 1;
    }
    try w.print(arena, "## Totals\n\n{d} distinct (architecture, source) pairs: {d} assembly, {d} C.\n", .{ seen.count(), n_asm, seen.count() - n_asm });

    const dest = "src/linalg/blas/blas1/axpy/coverage.md";
    try Io.Dir.cwd().writeFile(init.io, .{ .sub_path = dest, .data = try alignTables(arena, w.items) });
    std.debug.print("wrote {s}: {d} sources ({d} asm)\n", .{ dest, seen.count(), n_asm });
}

/// The gemm table columns: a label and the make variable of each precision.
const GemmColumn = struct { label: []const u8, suffix: []const u8 };

const copy_columns = [_]GemmColumn{
    .{ .label = "incopy", .suffix = "GEMMINCOPY" },
    .{ .label = "itcopy", .suffix = "GEMMITCOPY" },
    .{ .label = "oncopy", .suffix = "GEMMONCOPY" },
    .{ .label = "otcopy", .suffix = "GEMMOTCOPY" },
};

fn gemm(init: std.process.Init, arena: std.mem.Allocator) !void {
    var w: std.ArrayList(u8) = .empty;
    try w.appendSlice(arena,
        \\# `gemm` kernel coverage
        \\
        \\Generated by `tools/blas_asm/survey.zig gemm` from OpenBLAS `kernel/`;
        \\re-derive it rather than editing it. Each cell is the source that core's
        \\`KERNEL.<core>` selects for the make variable `<P>GEMM...`, falling back to
        \\the architecture's `KERNEL`, then to the `Makefile.L3` default (empty where
        \\that default is computed from the unroll sizes). `|` separates alternatives
        \\chosen by a conditional. Only the single-precision (`S`) and
        \\double-complex (`Z`) columns are shown for the packing routines; `D` and `C`
        \\name the same layouts in nearly every source.
        \\
        \\
    );

    var seen: std.StringArrayHashMapUnmanaged(bool) = .empty;
    const precisions = [_][]const u8{ "S", "D", "C", "Z" };

    for (arches) |arch| {
        const cores = try map.cores(arch) orelse continue;
        try w.print(arena, "## {s}\n\n| core |", .{arch});
        for (precisions) |p| try w.print(arena, " {s} kernel |", .{p});
        try w.appendSlice(arena, " S beta | D beta |");
        for (copy_columns) |c| try w.print(arena, " S {s} |", .{c.label});
        for (copy_columns) |c| try w.print(arena, " Z {s} |", .{c.label});
        try w.appendSlice(arena, "\n|---|");
        for (0..precisions.len + 2 + 2 * copy_columns.len) |_| try w.appendSlice(arena, "---|");
        try w.append(arena, '\n');
        for (cores) |core| {
            try w.print(arena, "| {s} |", .{core});
            for (precisions) |p| try gemmCell(arena, &w, &seen, arch, core, p, "GEMMKERNEL");
            for ([_][]const u8{ "S", "D" }) |p| try gemmCell(arena, &w, &seen, arch, core, p, "GEMM_BETA");
            for (copy_columns) |c| try gemmCell(arena, &w, &seen, arch, core, "S", c.suffix);
            for (copy_columns) |c| try gemmCell(arena, &w, &seen, arch, core, "Z", c.suffix);
            try w.append(arena, '\n');
        }
        try w.append(arena, '\n');
    }

    var n_asm: usize = 0;
    for (seen.values()) |is_asm| {
        if (is_asm) n_asm += 1;
    }
    try w.print(arena, "## Totals\n\n{d} distinct (architecture, source) pairs: {d} assembly, {d} C.\n", .{ seen.count(), n_asm, seen.count() - n_asm });

    const dest = "src/linalg/blas/blas3/gemm/coverage.md";
    try Io.Dir.cwd().writeFile(init.io, .{ .sub_path = dest, .data = try alignTables(arena, w.items) });
    std.debug.print("wrote {s}: {d} sources ({d} asm)\n", .{ dest, seen.count(), n_asm });
}

fn gemmCell(arena: std.mem.Allocator, w: *std.ArrayList(u8), seen: *std.StringArrayHashMapUnmanaged(bool), arch: []const u8, core: []const u8, p: []const u8, suffix: []const u8) !void {
    const key = try std.fmt.allocPrint(arena, "{s}{s}", .{ p, suffix });
    const v = try map.resolveKey(arch, core, key, "Makefile.L3");
    for (v) |s| try seen.put(arena, try std.fmt.allocPrint(arena, "{s}/{s}", .{ arch, s }), isAsm(s));
    try w.print(arena, " {s} |", .{try join(v)});
}

/// `text` with every table's columns padded to one width, which markdownlint's
/// aligned table style (MD060) wants.
fn alignTables(arena: std.mem.Allocator, text: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    var block: std.ArrayList([]const u8) = .empty;
    while (lines.next()) |line| {
        if (line.len > 0 and line[0] == '|') {
            try block.append(arena, line);
            continue;
        }
        try flushTable(arena, &out, block.items);
        block.clearRetainingCapacity();
        try out.appendSlice(arena, line);
        if (lines.peek() != null) try out.append(arena, '\n');
    }
    try flushTable(arena, &out, block.items);
    return out.items;
}

fn splitCells(arena: std.mem.Allocator, line: []const u8) ![]const []const u8 {
    var cells: std.ArrayList([]const u8) = .empty;
    var start: usize = 1;
    var i: usize = 1;
    while (i < line.len) : (i += 1) {
        if (line[i] == '\\') {
            i += 1;
        } else if (line[i] == '|') {
            try cells.append(arena, std.mem.trim(u8, line[start..i], " "));
            start = i + 1;
        }
    }
    return cells.items;
}

fn flushTable(arena: std.mem.Allocator, out: *std.ArrayList(u8), rows: []const []const u8) !void {
    if (rows.len == 0) return;
    var split: std.ArrayList([]const []const u8) = .empty;
    var widths: std.ArrayList(usize) = .empty;
    for (rows, 0..) |row, r| {
        const cells = try splitCells(arena, row);
        try split.append(arena, cells);
        for (cells, 0..) |c, k| {
            if (k >= widths.items.len) try widths.append(arena, 3);
            if (r != 1) widths.items[k] = @max(widths.items[k], c.len);
        }
    }
    for (split.items, 0..) |cells, r| {
        try out.append(arena, '|');
        for (cells, 0..) |c, k| {
            try out.append(arena, ' ');
            if (r == 1) {
                try out.appendNTimes(arena, '-', widths.items[k]);
            } else {
                try out.appendSlice(arena, c);
                try out.appendNTimes(arena, ' ', widths.items[k] - c.len);
            }
            try out.appendSlice(arena, " |");
        }
        try out.append(arena, '\n');
    }
}
