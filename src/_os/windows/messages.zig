pub fn msgToStr(msg: u32, buf: *[6]u8) []const u8 {
    return switch (@as(WinMsg, @fromBackingInt(@intCast(msg)))) {
        _ => std.fmt.bufPrint(buf, "0x{x:04}", .{msg}) catch unreachable,
        else => |e| @tagName(e),
    };
}
