const readIntBE = bytes.readIntBE;
const writeIntBE = bytes.writeIntBE;
const TagStr = types.TagStr;
const Offset32 = types.Offset32;

/// The list of all known table tags published in either the TTF or OTF specs.
///
/// See:
/// - https://learn.microsoft.com/en-us/typography/opentype/spec/
/// - https://developer.apple.com/fonts/TrueType-Reference-Manual/
pub const TableTag = enum {
    const Self = @This();

    /// Naming table. Required.
    name,
    /// Character to glyph mapping.  Required.
    cmap,
    /// Font header. May be missing in bitmap-only fonts, otherwise required.
    head,
    /// Horizontal header. May be missing in bitmap-only fonts, otherwise required.
    hhea,
    /// Horizontal metrics. May be missing in bitmap-only fonts, otherwise required.
    hmtx,
    /// Maximum profile. Optional per TTF, required per OpenType spec.
    maxp,
    /// PostScript table. Required.
    post,

    // ---
    // Classic glyph-based TrueType tables. Only required if not CFF.

    /// Glyph data. Only required if not CFF.
    glyf,
    /// Index to location. Only required if glyf is present
    loca,

    // ---
    // CFF TABLES: only required if not glyf

    /// Compact Font Format.
    CFF,
    /// Compact Font Format 2.
    CFF2,
    /// Vertical origin.  Optional.
    VORG,

    // ---
    // Platform-specific tables

    /// OS/2, required on OS/2 and Windows platforms only
    @"OS/2",

    // ---
    // OPTIONAL TTF TABLES:

    /// control value
    cvt,
    /// font program
    fpgm,
    /// horizontal device metrics, used on Mac only
    hdmx,
    /// kerning
    kern,
    /// control value program
    prep,
    /// Grid-fitting/scan-conversion
    gasp,

    // ---
    // SVG tables

    /// SVG table
    SVG,

    // ---
    // bitmap tables

    /// Embedded bitmap data
    EBDT,
    /// Embedded bitmap location data
    EBLC,
    /// Embedded bitmap scaling data
    EBSC,
    /// Color bitmap data
    CBDT,
    /// Color bitmap location data
    CBLC,
    /// Standard bitmap graphics
    sbix,

    // ---
    // Advanced typographic tables

    /// Baseline data
    BASE,
    /// Glyph definition data
    GDEF,
    /// Glyph positioning data
    GPOS,
    /// Glyph substitution data
    GSUB,
    /// Justification data
    JSTF,
    /// Math layout data
    MATH,

    // ---
    // OpenType variations tables

    /// Axis variations
    avar,
    /// CVT variations (TrueType outlines only)
    cvar,
    /// Font variations
    fvar,
    /// Glyph variations (TrueType outlines only)
    gvar,
    /// Horizontal metrics variations
    HVAR,
    /// Metrics variations
    MVAR,
    /// Style attributes (required for variable fonts, optional for non-variable fonts)
    STAT,
    /// Vertical metrics variations
    VVAR,

    // ---
    // Color tables

    /// Color table
    COLR,
    /// Color palette table
    CPAL,

    // ---
    // other OpenType tables

    /// Digital signature
    DSIG,
    /// Linear threshold data
    LTSH,
    /// Merge
    MERG,
    /// Metadata
    meta,
    /// PCL 5 data
    PCLT,
    /// Vertical device metrics
    VDMX,
    /// Vertical Metrics header
    vhea,
    /// Vertical Metrics
    vmtx,

    // ---
    // Miscellaneous tables: these are not implemented here and will be silently ignored

    /// FontForge extensions
    PfEd,
    /// FontForge timestamp
    FFTM,
    /// TeX details (generated by FontForge)
    TeX,
    /// X11 BDF fonts
    BDF,

    pub fn toInt(id: Self) u32 {
        var tag: TagStr = .{ .data = @splat(' ') };
        const name = @tagName(id);
        @memcpy(tag.data[0..name.len], name);
        return readIntBE(u32, &tag.data);
    }

    pub const Error = error{UnsupportedTag};

    pub fn fromInt(v: u32) Error!Self {
        var tag: TagStr = undefined;
        writeIntBE(u32, &tag.data, v);
        return fromTagStr(tag);
    }

    pub fn fromTagStr(tag: TagStr) Error!Self {
        return std.meta.stringToEnum(Self, tag.strip()) orelse error.UnsupportedTag;
    }
};

test "TableTag.toInt/fromInt round-trip, including a 3-letter tag needing space padding" {
    try zigstd.testExpectEqual(TableTag.cmap, try TableTag.fromInt(TableTag.cmap.toInt()));
    try zigstd.testExpectEqual(TableTag.cvt, try TableTag.fromInt(TableTag.cvt.toInt()));
    try zigstd.testExpectEqual(@as(u32, 0x63767420), TableTag.cvt.toInt()); // "cvt "
}

pub const ScalerType = enum {
    const Self = @This();

    ttf,
    ps,
    otf,

    pub const Error = error{UnsupportedScalerType};

    pub fn fromInt(v: u32) Error!Self {
        const alttrue: u32 = 0x00010000;
        const truestr = comptime readIntBE(u32, "true");
        const typ1 = comptime readIntBE(u32, "typ1");
        const otto = comptime readIntBE(u32, "OTTO");
        return switch (v) {
            alttrue, truestr => .ttf,
            typ1 => .ps,
            otto => .otf,
            else => error.UnsupportedScalerType,
        };
    }
};

test "ScalerType.fromInt recognizes all four accepted forms and rejects anything else" {
    try zigstd.testExpectEqual(ScalerType.ttf, try ScalerType.fromInt(0x00010000));
    try zigstd.testExpectEqual(ScalerType.ttf, try ScalerType.fromInt(readIntBE(u32, "true")));
    try zigstd.testExpectEqual(ScalerType.ps, try ScalerType.fromInt(readIntBE(u32, "typ1")));
    try zigstd.testExpectEqual(ScalerType.otf, try ScalerType.fromInt(readIntBE(u32, "OTTO")));
    try zigstd.testExpectError(error.UnsupportedScalerType, ScalerType.fromInt(0xDEADBEEF));
}

